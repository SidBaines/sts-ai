"""Narrow checked migration of original-policy rehearsal to a new zero residual.

Learned residuals are never silently ported across architectures. Actual source
rollout identity remains recorded; only a behavior-equivalent reference is added.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

import torch

from .strategic_data import read_buffer, write_buffer
from .training import load_checkpoint, file_identity


def verify_zero_prior_equivalence(source: dict[str, Any], reference: dict[str, Any]) -> None:
    known = {"typed_residual_ooc_v1", "typed_residual_ooc_v2"}
    if any(payload["model_config"].get("kind") not in known for payload in (source, reference)):
        raise ValueError("unsupported residual architecture for behavior-equivalence migration")
    if source["model_config"].get("encoder_version") != reference["model_config"].get("encoder_version"):
        raise ValueError("public feature layouts differ")
    for field in ("vocabulary_sha256", "bridge_version", "prior_config"):
        if source["model_config"].get(field) != reference["model_config"].get(field):
            raise ValueError(f"zero-residual reference differs: {field}")
    for role, payload in (("source", source), ("reference", reference)):
        state = payload["model_state"]
        for key in ("actor_score.2.weight", "actor_score.2.bias", "value_score.2.weight", "value_score.2.bias"):
            if key not in state or not bool((state[key] == 0).all()):
                raise ValueError(f"{role} has a learned/nonzero residual; migration requires a fresh zero residual")
    first = {key: value for key, value in source["model_state"].items() if key.startswith("prior.")}
    second = {key: value for key, value in reference["model_state"].items() if key.startswith("prior.")}
    if not first or set(first) != set(second):
        raise ValueError("frozen prior structures differ")
    if any(first[key].dtype != second[key].dtype or not torch.equal(first[key], second[key]) for key in first):
        raise ValueError("frozen prior weights differ")
    for key in ("typed_encoder_sha256", "legacy_bridge_sha256"):
        if source["metadata"]["policy_code_identity"][key] != reference["metadata"]["policy_code_identity"][key]:
            raise ValueError(f"public feature implementation differs: {key}")
    for key in ("python_interface_sha256", "native_module_sha256"):
        if source["metadata"]["training_environment"].get(key) != reference["metadata"]["training_environment"].get(key):
            raise ValueError(f"environment differs: {key}")


def migrate_reference_buffer(source_buffer: Path, source_checkpoint: Path,
                             reference_checkpoint: Path, output: Path) -> dict[str, Any]:
    if output.exists():
        raise ValueError("reference migration must use a new output path")
    source, reference = load_checkpoint(source_checkpoint), load_checkpoint(reference_checkpoint)
    verify_zero_prior_equivalence(source, reference)
    rows, metadata = read_buffer(source_buffer)
    source_sha, reference_sha = file_identity(source_checkpoint), file_identity(reference_checkpoint)
    if metadata.get("source_checkpoint_sha256") != source_sha:
        raise ValueError("rehearsal buffer was generated by a different source policy")
    # Keep source identities truthful: these public trajectories were produced
    # by the old source. The new reference has separately checked equal behavior.
    metadata = {**metadata, "reference_checkpoint_sha256": reference_sha,
                "reference_policy_code_identity": reference["metadata"]["policy_code_identity"],
                "reference_migration": {"version": "checked_zero_residual_reference_v1",
                    "source_buffer_sha256": file_identity(source_buffer), "source_checkpoint_sha256": source_sha,
                    "reference_checkpoint_sha256": reference_sha, "frozen_prior_bitwise_equal": True,
                    "actor_and_value_residual_outputs_zero": True,
                    "note": "Architecture/hidden residual weights change; original behavior and public features are verified equal."}}
    output_sha = write_buffer(output, rows, metadata)
    return {"rows": len(rows), "output_sha256": output_sha, "reference_migration": metadata["reference_migration"]}
